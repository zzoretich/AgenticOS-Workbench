#!/usr/bin/env node
'use strict';
/**
 * build-codex-plugin.js — generates codex-plugin/, the Codex CLI plugin, from plugin/ (the Claude Code plugin).
 *
 * Design docs/superpowers/specs/2026-09-23-codex-plugin-design.md (D1–D3). Codex reads
 * .agents/plugins/marketplace.json before the Claude marketplace file, so one repository serves each host its own
 * folder: Claude Code installs plugin/, Codex installs codex-plugin/. The output is committed because a marketplace
 * install copies files and runs nothing; `--check` rebuilds in memory and exits 1 when the committed tree differs,
 * and build-codex-plugin.test.js runs the same comparison with the rest of the suite.
 *
 *   node tools/build-codex-plugin.js           rewrite codex-plugin/ from scratch
 *   node tools/build-codex-plugin.js --check   compare only
 *
 * Nothing in the output names a path on the building machine: hooks use ${PLUGIN_ROOT}, the MCP server a launcher
 * relative to the plugin folder, and skills `<plugin root>` (cli/codex-host.js, target 'plugin').
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const CH = require('../cli/codex-host.js');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'plugin');
const OUT_DIR = path.join(ROOT, 'codex-plugin');
const EXECUTABLE = new Set(['bin/aos']);
const IGNORED = new Set(['.DS_Store']);

const json = (obj) => Buffer.from(JSON.stringify(obj, null, 2) + '\n');
const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));

/** Every file under `dir` as a sorted list of '/'-separated relative paths. */
function listFiles(dir, base = dir) {
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return []; }
  const out = [];
  for (const e of entries) {
    if (IGNORED.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...listFiles(p, base));
    else if (e.isFile()) out.push(path.relative(base, p).split(path.sep).join('/'));
  }
  return out.sort();
}

function manifest() {
  const pkg = readJson(path.join(ROOT, 'package.json'));
  const claude = readJson(path.join(SRC, '.claude-plugin', 'plugin.json'));
  return {
    name: CH.PLUGIN_NAME,
    version: pkg.version,
    description: claude.description,
    author: claude.author,
    homepage: claude.homepage,
    repository: claude.homepage,
    license: pkg.license,
    keywords: ['memory', 'second-brain', 'obsidian', 'recall', 'session-capture', 'telemetry'],
    skills: './skills/',
    hooks: './hooks/hooks.json',
    mcpServers: './.mcp.json',
    interface: {
      displayName: 'AgenticOS Workbench',
      shortDescription: 'A second brain for Codex, shared with Claude Code',
      longDescription: 'Persistent memory for Codex sessions in an Obsidian vault on your machine: brain context on every prompt, '
        + 'session capture into memory at the end, recall over the whole vault through the agenticos MCP server, and the same '
        + 'vocabulary as under Claude Code ($agenticos:wrap, $agenticos:remember, $agenticos:recall). Run `aos init` first; '
        + 'until then every hook and tool of this plugin exits quietly.',
      developerName: claude.author.name,
      category: 'Productivity',
      capabilities: ['Interactive', 'Read', 'Write'],
      websiteURL: claude.homepage,
      defaultPrompt: [
        'What did we decide about this project last time?',
        'Show my brain state',
        'Wrap this session into memory',
      ],
    },
  };
}

function hooks() {
  const doc = {
    description: 'AgenticOS Workbench for Codex: brain context injection, conventions, session capture, telemetry, and dashboard refresh. '
      + 'Every command runs bin/aos with AOS_HOST=codex; bin/aos exits 0 when the workbench has not been initialized, so a hook never '
      + 'fails a session. Generated by tools/build-codex-plugin.js from cli/codex-host.js HOOKS.',
    hooks: {},
  };
  for (const [event, cmds] of CH.HOOKS) {
    doc.hooks[event] = [{ hooks: cmds.map(([name, timeout]) => ({ type: 'command', command: CH.pluginHookCommand(name), timeout })) }];
  }
  return doc;
}

/** The 17 commands and 9 skills of plugin/ as Codex plugin skills, read back from a scratch directory. */
function skills() {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aos-codex-plugin-'));
  try {
    CH.generateSkills({ pluginDir: SRC, dir: tmp, target: 'plugin' });
    return new Map(listFiles(tmp).map((rel) => [`skills/${rel}`, fs.readFileSync(path.join(tmp, rel))]));
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

/** relative path → Buffer, sorted. */
function build() {
  const files = new Map([
    ['.codex-plugin/plugin.json', json(manifest())],
    ['.mcp.json', json(CH.pluginMcpServers())],
    ['bin/aos', fs.readFileSync(path.join(SRC, 'bin', 'aos'))],
    ['hooks/hooks.json', json(hooks())],
    ...skills(),
  ]);
  return new Map([...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

/** Differences between a build and a directory, as 'missing <p>' / 'differs <p>' / 'stale <p>' / 'not executable <p>'. */
function check(files, dir = OUT_DIR) {
  const problems = [];
  const onDisk = new Set(listFiles(dir));
  for (const [rel, content] of files) {
    const p = path.join(dir, rel);
    if (!onDisk.has(rel)) problems.push(`missing ${rel}`);
    else if (!fs.readFileSync(p).equals(content)) problems.push(`differs ${rel}`);
    else if (EXECUTABLE.has(rel) && !(fs.statSync(p).mode & 0o111)) problems.push(`not executable ${rel}`);
  }
  for (const rel of onDisk) if (!files.has(rel)) problems.push(`stale ${rel}`);
  return problems;
}

function write(files, dir = OUT_DIR) {
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, content] of files) {
    const p = path.join(dir, rel);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content, { mode: EXECUTABLE.has(rel) ? 0o755 : 0o644 });
    fs.chmodSync(p, EXECUTABLE.has(rel) ? 0o755 : 0o644);
  }
}

module.exports = { build, check, write, listFiles, OUT_DIR };

if (require.main === module) {
  const files = build();
  if (process.argv.includes('--check')) {
    const problems = check(files);
    for (const p of problems) process.stderr.write(`codex-plugin: ${p}\n`);
    if (problems.length) process.stderr.write('codex-plugin/ is out of date — run: npm run build:codex-plugin\n');
    else process.stdout.write(`codex-plugin/ is up to date (${files.size} files)\n`);
    process.exit(problems.length ? 1 : 0);
  }
  write(files);
  process.stdout.write(`${files.size} files written to codex-plugin/\n`);
}
